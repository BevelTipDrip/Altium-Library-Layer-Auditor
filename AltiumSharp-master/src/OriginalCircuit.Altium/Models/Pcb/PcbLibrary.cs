using OriginalCircuit.Altium.Diagnostics;
using OriginalCircuit.Altium.Serialization.Writers;

namespace OriginalCircuit.Altium.Models.Pcb;

/// <summary>
/// Implementation of a PCB footprint library.
/// </summary>
public sealed class PcbLibrary : IPcbLibrary
{
    private readonly List<IPcbComponent> _components = new();
    private readonly Dictionary<string, IPcbComponent> _componentsByName = new(StringComparer.OrdinalIgnoreCase);
    private IReadOnlyList<IComponent>? _allComponentsCache;

    /// <summary>
    /// Diagnostics collected during file reading (warnings about skipped records, parse errors, etc.).
    /// </summary>
    public IReadOnlyList<AltiumDiagnostic> Diagnostics { get; internal set; } = Array.Empty<AltiumDiagnostic>();

    /// <summary>
    /// Section keys mapping component names to their OLE storage section key strings.
    /// Needed when component names exceed 31 chars or contain special characters.
    /// </summary>
    internal Dictionary<string, string>? SectionKeys { get; set; }

    /// <summary>
    /// Library-level parameters from the Library/Data stream.
    /// Contains the full set of PCB library metadata (layer stacks, design rules, etc.).
    /// When null, defaults (HEADER + WEIGHT) are used for new files.
    /// </summary>
    internal Dictionary<string, string>? LibraryParameters { get; set; }

    /// <summary>
    /// Library-level parameters as an ordered, authorable key/value list — the canonical representation,
    /// preserving key order and the duplicate keys that <see cref="LibraryParameters"/> (a flattened
    /// convenience view) collapses (the header concatenates repeated <c>RECORD=</c>-delimited layer-stack
    /// sub-records). Written verbatim when non-null; null falls back to <see cref="LibraryParameters"/>.
    /// </summary>
    public List<KeyValuePair<string, string>>? LibraryParametersOrdered { get; set; }

    private PcbLayerStack? _layerStackCache;

    /// <summary>
    /// The layer stack (layer names, including any renamed mechanical layers like "Courtyard" or
    /// "Assembly") parsed from <see cref="LibraryParameters"/>. Null if the library carries no layer
    /// stack header. See <see cref="PcbLayerStack.FromBoardParameters"/> for the parsing details.
    /// </summary>
    public PcbLayerStack? LayerStack => _layerStackCache ??= PcbLayerStack.FromBoardParameters(LibraryParameters);

    /// <summary>
    /// Unique identifier for this library (8-character random string).
    /// Generated by Altium when the library is created.
    /// </summary>
    public string UniqueId { get; set; } = GenerateUniqueId();

    /// <summary>
    /// 3D models embedded in this library. Each model contains STEP data
    /// and metadata referenced by <see cref="PcbComponentBody.ModelId"/>.
    /// </summary>
    public List<PcbModel> Models { get; } = new();

    /// <summary>
    /// Additional OLE streams within the Library storage, preserved for round-trip fidelity.
    /// Known streams: "ComponentParamsTOC" (table of contents for component parameters),
    /// "EmbeddedFonts" (font data), "PadViaLibrary" (pad/via templates).
    /// Key format: "StreamName" or "SubStorageName/StreamName" -> byte data.
    /// Empty by default for from-scratch creation (these streams are optional).
    /// </summary>
    public Dictionary<string, byte[]>? AdditionalLibraryStreams { get; set; }

    /// <summary>
    /// Additional root-level OLE storages with their streams, preserved for round-trip fidelity.
    /// Known storages: "FileVersionInfo" (file format version metadata).
    /// Key format: "StorageName/StreamName" -> byte data.
    /// Empty by default for from-scratch creation (these streams are optional).
    /// </summary>
    public Dictionary<string, byte[]>? AdditionalRootStreams { get; set; }

    /// <summary>
    /// Library sub-storages that Altium always writes as empty (Header count 0 + empty Data): by default
    /// <c>Textures</c> and <c>ModelsNoEmbed</c>. Emitted explicitly (rather than replayed from
    /// <see cref="AdditionalLibraryStreams"/>) so from-scratch libraries carry them too. The reader drops
    /// a name from this set and falls back to verbatim capture if a source file ever has non-empty content.
    /// </summary>
    public HashSet<string> EmptyLibrarySubStorages { get; } =
        new(StringComparer.OrdinalIgnoreCase) { "Textures", "ModelsNoEmbed" };

    /// <summary>
    /// The root <c>FileVersionInfo</c> version-message cache, modeled as a typed record.
    /// </summary>
    public PcbFileVersionInfo FileVersionInfo { get; set; } = new();

    /// <summary>
    /// The <c>Library/LayerKindMapping</c> metadata Altium writes in every PcbLib. Modeled as a typed
    /// record (rather than an opaque stream) so it round-trips and is emitted for from-scratch libraries.
    /// </summary>
    public PcbLayerKindMapping LayerKindMapping { get; set; } = new();

    /// <summary>
    /// The <c>Library/PadViaLibrary</c> local pad/via template-library identity. Modeled so it round-trips
    /// and is authored for from-scratch libraries.
    /// </summary>
    public PcbPadViaLibrary PadViaLibrary { get; set; } = new();

    /// <summary>
    /// The <c>Library/ComponentParamsTOC</c> per-footprint summary table. Rebuilt from the components on
    /// write; populated on read for inspection.
    /// </summary>
    public List<PcbComponentParamsTocEntry> ComponentParamsToc { get; } = new();

    /// <inheritdoc />
    public IReadOnlyList<IPcbComponent> Components => _components;

    /// <inheritdoc />
    public IReadOnlyList<IComponent> AllComponents =>
        _allComponentsCache ??= _components.Cast<IComponent>().ToList();

    /// <inheritdoc />
    public int Count => _components.Count;

    /// <inheritdoc />
    public IPcbComponent? this[string name] =>
        _componentsByName.TryGetValue(name, out var component) ? component : null;

    /// <inheritdoc />
    public bool Contains(string name) => _componentsByName.ContainsKey(name);

    /// <inheritdoc />
    public void Add(IPcbComponent component)
    {
        ArgumentNullException.ThrowIfNull(component);

        if (string.IsNullOrEmpty(component.Name))
            throw new ArgumentException("Component must have a name", nameof(component));

        if (_componentsByName.ContainsKey(component.Name))
            throw new ArgumentException($"A component named '{component.Name}' already exists", nameof(component));

        _components.Add(component);
        _componentsByName[component.Name] = component;
        _allComponentsCache = null; // Invalidate cache
    }

    /// <inheritdoc />
    public bool Remove(string name)
    {
        if (!_componentsByName.TryGetValue(name, out var component))
            return false;

        _components.Remove(component);
        _componentsByName.Remove(name);
        _allComponentsCache = null; // Invalidate cache
        return true;
    }

    /// <inheritdoc />
    public async ValueTask SaveAsync(string path, OriginalCircuit.Eda.Models.SaveOptions? options = null, CancellationToken cancellationToken = default)
    {
        await using var stream = new FileStream(path, FileMode.Create, FileAccess.Write, FileShare.None, 4096, useAsync: true);
        await SaveAsync(stream, options, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public async ValueTask SaveAsync(Stream stream, OriginalCircuit.Eda.Models.SaveOptions? options = null, CancellationToken cancellationToken = default)
    {
        var writer = new PcbLibWriter();
        await writer.WriteAsync(this, stream, cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public ValueTask DisposeAsync()
    {
        // No unmanaged resources to dispose
        return ValueTask.CompletedTask;
    }

    /// <summary>
    /// Generates a fresh 8-character library identifier (8 uniformly random uppercase ASCII letters),
    /// matching Altium's generation. Used for the FileHeader Identity field on new libraries.
    /// </summary>
    internal static string GenerateUniqueId()
    {
        const string chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
        var random = Random.Shared;
        return string.Create(8, random, (span, rng) =>
        {
            for (var i = 0; i < span.Length; i++)
                span[i] = chars[rng.Next(chars.Length)];
        });
    }
}
